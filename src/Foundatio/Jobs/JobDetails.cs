using System;
using System.Collections.Generic;
using System.Collections.ObjectModel;
using System.Diagnostics.CodeAnalysis;
using Foundatio.Jobs.Store;
using Foundatio.Serializer;

namespace Foundatio.Jobs;

/// <summary>
/// A job as an app sees it through <see cref="IJobClient"/>: its state, progress and result. Safe to return from an
/// API: it leaves out the claim token that fences workers, the lease and the serialized arguments.
/// </summary>
public sealed class JobDetails
{
    private readonly ReadOnlyMemory<byte> _payload;
    private readonly ISerializer? _serializer;

    /// <summary>Creates details with no arguments, for example to stub <see cref="IJobClient"/> in a test.</summary>
    public JobDetails()
    {
    }

    [SetsRequiredMembers]
    internal JobDetails(JobInfo job, ISerializer serializer)
    {
        Id = job.Id;
        Name = job.Name;
        State = job.State;
        Attempt = job.Attempt;
        CreatedAt = job.CreatedAt;
        AvailableAt = job.AvailableAt;
        UpdatedAt = job.UpdatedAt;
        StartedAt = job.StartedAt;
        CompletedAt = job.CompletedAt;
        Progress = job.Progress;
        Message = job.Message;
        Error = job.Error;
        CancellationRequested = job.CancellationRequested;
        ScheduleName = job.ScheduleName;
        CorrelationId = job.CorrelationId;
        WorkerId = job.WorkerId;
        Headers = job.Headers;
        _payload = job.Payload;
        _serializer = serializer;
    }

    /// <summary>Unique within the store. Generated by Foundatio, or chosen by the caller through <see cref="EnqueueOptions.JobId"/>.</summary>
    public required string Id { get; init; }

    /// <summary>The job's stable name: its arguments type's name, or for a job without arguments, the job type's.</summary>
    public required string Name { get; init; }

    /// <summary>Where the job is in its lifecycle.</summary>
    public JobState State { get; init; }

    /// <summary>How many times the job has started, including a current run.</summary>
    public int Attempt { get; init; }

    /// <summary>When the job was enqueued.</summary>
    public DateTimeOffset CreatedAt { get; init; }

    /// <summary>The job is not started before this time. For a CRON job this is the scheduled occurrence.</summary>
    public DateTimeOffset AvailableAt { get; init; }

    /// <summary>When the job last changed.</summary>
    public DateTimeOffset UpdatedAt { get; init; }

    /// <summary>When the job first started running.</summary>
    public DateTimeOffset? StartedAt { get; init; }

    /// <summary>When the job succeeded, failed or was cancelled.</summary>
    public DateTimeOffset? CompletedAt { get; init; }

    /// <summary>The last reported progress percentage.</summary>
    public int? Progress { get; init; }

    /// <summary>The last progress or result message.</summary>
    public string? Message { get; init; }

    /// <summary>The error from the most recent failed attempt.</summary>
    public string? Error { get; init; }

    /// <summary>Whether someone asked to cancel the job.</summary>
    public bool CancellationRequested { get; init; }

    /// <summary>The CRON schedule that created the job, if any.</summary>
    public string? ScheduleName { get; init; }

    /// <summary>Links the job to the request, message or job that enqueued it.</summary>
    public string? CorrelationId { get; init; }

    /// <summary>The worker running the job, while it runs.</summary>
    public string? WorkerId { get; init; }

    /// <summary>Headers the job was enqueued with, including the W3C trace context. Empty when there are none.</summary>
    public IReadOnlyDictionary<string, string> Headers { get; init; } = ReadOnlyDictionary<string, string>.Empty;

    /// <summary>
    /// Deserializes the job's arguments as <typeparamref name="TArgs"/> with the jobs serializer, which throws when they
    /// cannot be read as that type. Returns null for a job without arguments.
    /// </summary>
    public TArgs? GetArguments<TArgs>() where TArgs : class
    {
        if (_payload.IsEmpty || _serializer is null)
            return null;

        return _serializer.Deserialize<TArgs?>(_payload);
    }

    /// <inheritdoc />
    public override string ToString() => $"{Name} {Id} ({State})";
}
